function paragraph(ch: number, i: number): string {
  // 每段 2–4 句，按章號和段號取，保證確定且各章不同
  const n = 2 + ((ch + i) % 3);
  let out = '';
  for (let k = 0; k < n; k++) out += SENTENCES[(ch * 17 + i * 5 + k * 11 + ch * i) % SENTENCES.length]!;
  return out;
}

export function buildReadingBook(paragraphsPerChapter = 14, generator?: string): Uint8Array {
  return buildEpub({
    generator,
    title: READING_TITLE,
    author: READING_AUTHOR,
    lang: 'zh-TW',
    chapters: CHAPTER_TITLES.map((title, ch) => ({
      title,
      paragraphs: Array.from({ length: paragraphsPerChapter }, (_, i) => paragraph(ch, i)),
    })),
  });
}
